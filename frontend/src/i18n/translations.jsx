export function vgTranslateText(text, language) {
  if (language !== "tr") return text;
  return VG_TR_DICTIONARY[text] || text;
}

export function translateLiveEventInfo(info, language) {
  const text = String(info || "-");
  if (language !== "tr") return text;
  return LIVE_EVENT_INFO_TR[text] || vgTranslateText(text, language);
}

export function translateLogValue(value, language) {
  const raw = String(value ?? "-");
  if (raw === "-" || raw === "") return "-";
  return vgTranslateText(raw.toUpperCase ? raw.toUpperCase() : raw, language);
}

