import os
import csv
import json
import statistics
import datetime
from collections import Counter

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
LOG_FILE = os.path.join(BASE_DIR, "vguard_logs.json")
EVAL_JSON_FILE = os.path.join(BASE_DIR, "vguard_evaluation_report.json")
EVAL_CSV_FILE = os.path.join(BASE_DIR, "vguard_evaluation_summary.csv")


def load_runtime_logs(log_file=LOG_FILE):
    records = []
    if not os.path.exists(log_file):
        return records

    with open(log_file, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
                if isinstance(item, dict):
                    records.append(item)
            except json.JSONDecodeError:
                continue
    return records


def safe_float(value, default=0.0):
    try:
        return float(value)
    except Exception:
        return default


def build_evaluation_report(records):
    total = len(records)
    by_type = Counter(str(r.get("type", "UNKNOWN")) for r in records)
    by_severity = Counter(str(r.get("severity", "UNKNOWN")) for r in records)
    by_action = Counter(str(r.get("action", "UNKNOWN")) for r in records)
    by_verdict = Counter(str(r.get("verdict", "UNKNOWN")) for r in records)
    by_module = Counter(str(r.get("module", "UNKNOWN")) for r in records)

    dropped = sum(1 for r in records if str(r.get("verdict", "")).upper() == "DROP")
    accepted = sum(1 for r in records if str(r.get("verdict", "")).upper() == "ACCEPT")
    warnings = sum(1 for r in records if str(r.get("action", "")).upper() == "WARNING")
    high_or_critical = sum(
        1 for r in records
        if str(r.get("severity", "")).upper() in {"HIGH", "CRITICAL"}
    )

    latencies = [
        safe_float(r.get("latency_ms"))
        for r in records
        if "latency_ms" in r and str(r.get("latency_ms", "")).strip() != ""
    ]

    latency_summary = {
        "count": len(latencies),
        "average_ms": round(statistics.mean(latencies), 3) if latencies else 0.0,
        "median_ms": round(statistics.median(latencies), 3) if latencies else 0.0,
        "min_ms": round(min(latencies), 3) if latencies else 0.0,
        "max_ms": round(max(latencies), 3) if latencies else 0.0,
    }

    # This is a runtime-log summary. Ground-truth accuracy requires a labeled test set.
    report = {
        "project": "v-Guard",
        "report_type": "IDS/IPS Runtime Evaluation Report",
        "created_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "source_log_file": LOG_FILE,
        "summary": {
            "total_events": total,
            "accepted_events": accepted,
            "dropped_events": dropped,
            "warning_events": warnings,
            "high_or_critical_events": high_or_critical,
        },
        "latency_summary": latency_summary,
        "event_type_distribution": dict(by_type),
        "severity_distribution": dict(by_severity),
        "action_distribution": dict(by_action),
        "verdict_distribution": dict(by_verdict),
        "module_distribution": dict(by_module),
        "notes": [
            "Generated from v-Guard runtime logs.",
            "ACCEPT/DROP counts measure prevention behavior during the demo/test run.",
            "Latency values come from packet verdict processing logs when available.",
            "Formal accuracy, precision, recall and F1 are generated by ai_trainer.py from the labeled dataset."
        ]
    }
    return report


def save_evaluation_report(report, json_file=EVAL_JSON_FILE, csv_file=EVAL_CSV_FILE):
    with open(json_file, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=4, ensure_ascii=False)

    rows = []
    for section_name in [
        "summary", "latency_summary", "event_type_distribution",
        "severity_distribution", "action_distribution", "verdict_distribution",
        "module_distribution"
    ]:
        section = report.get(section_name, {})
        for key, value in section.items():
            rows.append({"section": section_name, "metric": key, "value": value})

    with open(csv_file, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["section", "metric", "value"])
        writer.writeheader()
        writer.writerows(rows)

    return json_file, csv_file


def generate_from_log_file(log_file=LOG_FILE):
    records = load_runtime_logs(log_file)
    report = build_evaluation_report(records)
    json_file, csv_file = save_evaluation_report(report)
    return report, json_file, csv_file


def main():
    print("[*] v-Guard Evaluation Report Generator")
    records = load_runtime_logs()
    if not records:
        print(f"[!] No runtime logs found in {LOG_FILE}")
        return
    report = build_evaluation_report(records)
    json_file, csv_file = save_evaluation_report(report)
    print("[+] Evaluation report generated.")
    print(f"    Events analyzed : {report['summary']['total_events']}")
    print(f"    JSON report     : {json_file}")
    print(f"    CSV summary     : {csv_file}")


if __name__ == "__main__":
    main()
